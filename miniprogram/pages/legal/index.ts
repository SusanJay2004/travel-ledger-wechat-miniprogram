  '我们保存你主动填写的用户名、签名、头像、好友关系、行程、账单、通知和操作记录，用于提供记账、协作、恢复与安全保障。',
  '头像会上传至微信云存储；资料、行程名称和账单事件会在服务端进行内容安全检查。我们不读取通讯录，不提供支付或代收款。',
  '你可以在“我的—设置与隐私”注销账号。注销会删除个人入口和社交数据，并匿名化共享账务历史；金额记录为保护其他同行人的合法账务需求而保留。',
