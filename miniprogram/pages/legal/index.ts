interface LegalData {
  body: readonly string[];
  title: string;
}

type LegalMethods = Record<never, never>;

Page<LegalData, LegalMethods>({
  data: { body: [], title: '' },

  onLoad(query: Record<string, string | undefined>) {
    const terms = query['type'] === 'terms';
    const title = terms ? '用户协议' : '隐私保护指引';
    void wx.setNavigationBarTitle({ title });
    this.setData({ body: terms ? TERMS : PRIVACY, title });
  },
});

